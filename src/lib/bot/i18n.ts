export function t(lang: Language | null | undefined, key: keyof typeof translations.en, params?: Record<string, string>): string {
  const selectedLang = lang || "am"; // Default to Amharic
  let text = translations[selectedLang][key] || translations.en[key] || key;
  
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, v);
    }
  }
  return text;
}
